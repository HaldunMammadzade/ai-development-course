import type {
  CheckQuestionBlock,
  ConceptDefinition,
  ConceptPrerequisite,
  ExerciseDefinition,
  LessonBlock,
  LessonDefinition,
  ReadingBlock,
  RecapBlock,
} from "@platform/types";

function reading(position: number, markdown: string, conceptSlugs: string[]): ReadingBlock {
  return { type: "reading", position, markdown, conceptSlugs };
}

function check(
  position: number,
  prompt: string,
  rubric: string[],
  conceptSlugs: string[],
  difficulty: CheckQuestionBlock["difficulty"],
): CheckQuestionBlock {
  return { type: "check_question", position, prompt, rubric, conceptSlugs, difficulty };
}

function recap(position: number, points: string[], practicePrompt: string): RecapBlock {
  return { type: "recap", position, points, practicePrompt };
}

function lesson(input: {
  slug: string;
  title: string;
  objective: string;
  position: number;
  minutes: number;
  primary: string[];
  supporting?: string[];
  paragraphs: string[];
  question: string;
  rubric: string[];
  points: string[];
  practice: string;
}): LessonDefinition {
  const concepts = [
    ...input.primary.map((conceptSlug) => ({ conceptSlug, role: "primary" as const })),
    ...(input.supporting ?? []).map((conceptSlug) => ({
      conceptSlug,
      role: "supporting" as const,
    })),
  ];
  const blocks: LessonBlock[] = [
    reading(1, input.paragraphs.join("\n\n"), concepts.map((link) => link.conceptSlug)),
    check(2, input.question, input.rubric, [input.primary[0] ?? "react.basics"], "beginner"),
    recap(3, input.points, input.practice),
  ];
  return {
    slug: input.slug,
    title: input.title,
    objective: input.objective,
    position: input.position,
    estimatedMinutes: input.minutes,
    status: "published",
    concepts,
    blocks,
  };
}

function choiceExercise(input: {
  slug: string;
  lessonSlug: string;
  conceptSlug: string;
  title: string;
  prompt: string;
  answer: string;
  options: Array<[string, string]>;
  difficulty: ExerciseDefinition["difficulty"];
  position: number;
}): ExerciseDefinition {
  return {
    slug: input.slug,
    lessonSlug: input.lessonSlug,
    conceptSlug: input.conceptSlug,
    title: input.title,
    prompt: input.prompt,
    instructions: "Bir variant seç. Düzgünlüyü server yoxlayır.",
    type: "multiple_choice",
    language: null,
    difficulty: input.difficulty,
    position: input.position,
    starterCode: null,
    published: true,
    options: input.options.map(([id, label]) => ({ id, label })),
    rules: [
      {
        type: "choice_equals",
        optionId: input.answer,
        points: 100,
        feedback: "Bu variant bu sualın cavabı deyil. Dərsdəki fərqi bir daha oxu.",
      },
    ],
  };
}

function codeExercise(input: {
  slug: string;
  lessonSlug: string;
  conceptSlug: string;
  title: string;
  prompt: string;
  instructions: string;
  difficulty: ExerciseDefinition["difficulty"];
  position: number;
  starterCode: string | null;
  language: "javascript" | null;
  rules: ExerciseDefinition["rules"];
}): ExerciseDefinition {
  return {
    slug: input.slug,
    lessonSlug: input.lessonSlug,
    conceptSlug: input.conceptSlug,
    title: input.title,
    prompt: input.prompt,
    instructions: input.instructions,
    type: "code_text",
    language: input.language,
    difficulty: input.difficulty,
    position: input.position,
    starterCode: input.starterCode,
    published: true,
    options: [],
    rules: input.rules,
  };
}

